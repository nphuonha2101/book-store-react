import nextEnv from "@next/env";

const { loadEnvConfig } = nextEnv;
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

// Load .env, .env.local, etc. so `npm run dev` and `npm run build` both produce
// a service worker matching the Firebase project configured for the build.
loadEnvConfig(process.cwd());

const config = {
    apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY ?? "",
    authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN ?? "",
    projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID ?? "",
    storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET ?? "",
    messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID ?? "",
    appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID ?? "",
};

const source = `/* Generated by scripts/generate-firebase-sw.mjs — do not edit. */
importScripts('https://www.gstatic.com/firebasejs/12.19.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/12.19.0/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(config, null, 4)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
    const notificationTitle = payload.notification?.title || 'Thông báo';
    const notificationOptions = {
        body: payload.notification?.body,
        icon: '/Logo.svg',
        data: { actionUrl: payload.data?.actionUrl || '/' },
    };
    self.registration.showNotification(notificationTitle, notificationOptions);
});

self.addEventListener('notificationclick', (event) => {
    event.notification.close();
    const actionUrl = event.notification.data?.actionUrl || '/';
    event.waitUntil(clients.openWindow(actionUrl));
});
`;

const outDir = path.join(process.cwd(), "public");
await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, "firebase-messaging-sw.js"), source, "utf8");
console.log("Generated public/firebase-messaging-sw.js");
